const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const lock = require('../lib/engine-lock');
const source = fs.readFileSync(require.resolve('../lib/automation'), 'utf8').replace(/\r\n/g, '\n');
const start = source.indexOf('function ensureOutcomeCount(');
const context = vm.createContext({});
vm.runInContext(source.slice(start, source.indexOf('\n}\n', start) + 2), context);
const job = lock.beginJob('autobtd6', 'black-border-sweep');
lock.pushLog(job, 'screen VICTORY!');
assert.equal(job.victories, 0);
lock.pushLog(job, 'screen INGAME!');
lock.pushLog(job, 'screen VICTORY_SUMMARY!');
lock.pushLog(job, 'VICTORY_CONFIRMED map=example');
assert.equal(job.victories, 0, 'Sweep victory waits for authoritative medal confirmation');
context.ensureOutcomeCount(job, 'victory');
context.ensureOutcomeCount(job, 'victory');
assert.equal(job.victories, 1);
lock.pushLog(job, 'screen INGAME!');
lock.pushLog(job, 'screen VICTORY!');
context.ensureOutcomeCount(job, 'victory');
assert.equal(job.victories, 2, 'A second confirmed run counts exactly once');
lock.pushLog(job, 'screen INGAME!');
lock.pushLog(job, 'screen DEFEAT!');
context.ensureOutcomeCount(job, 'defeat');
assert.equal(job.defeats, 1, 'Observed defeats still update immediately without double counting');
lock.endJob(job);
const farm = lock.beginJob('autobtd6', 'xp');
lock.pushLog(farm, 'screen INGAME!');
lock.pushLog(farm, 'screen VICTORY!');
assert.equal(farm.victories, 1, 'Non-medal farming keeps its game-outcome counter');
lock.endJob(farm);
console.log('Sweep outcome count checks passed.');
