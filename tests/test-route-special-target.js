const assert = require('node:assert/strict');
const { validateRoute } = require('../lib/route-validation');
const catalog = { monkeys: { dartling: { type: 'military' } }, heros: {} };
const text = 'place dartling gun at 100, 200\nspecial gun to 600, 700 at 300, 400\n';
assert.deepEqual(validateRoute(text, 'hard', catalog), []);
const second = text.replace('special gun', 'special2 gun');
assert.deepEqual(validateRoute(second, 'hard', catalog), []);
assert.ok(validateRoute('special2 missing to 600, 700\n', 'hard', catalog).length);
assert.ok(validateRoute(second.replace('special2', 'special3'), 'hard', catalog).length);
const { strategySignature } = require('../lib/route-validation');
assert.equal(strategySignature(second), strategySignature(second.replaceAll('gun', 'renamed')));
assert.notEqual(strategySignature(second), strategySignature(text));
assert.ok(validateRoute(text.replace('600, 700', '600'), 'hard', catalog).length);
assert.ok(validateRoute('special missing to 600, 700\n', 'hard', catalog).length);
console.log('Targeted special route grammar checks passed');
assert.deepEqual(validateRoute('place dartling gun at 100, 200\nretarget gun reverse at 300, 400\n', 'hard', catalog), []);
assert.ok(validateRoute('place dartling gun at 100, 200\nretarget gun reverse to 600, 700\n', 'hard', catalog).length);
