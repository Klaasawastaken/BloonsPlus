const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require.resolve('../assets/app/app.js'), 'utf8');
const start = source.indexOf('function activityTimestamp(');
assert.notEqual(start, -1, 'Production activity clock helper must exist');
const end = source.indexOf('\n}\n', start) + 2;
const context = vm.createContext({ activitySeenAt: new Map(), Date });
vm.runInContext(source.slice(start, end), context);
const time = (at, key, now) => context.activityTimestamp(at, key, now);
const now = 1791226200000;
assert.equal(time(new Date(now - 12000).toISOString(), 'iso', now), now - 12000);
assert.equal(time(now / 1000, 'seconds', now), now);
assert.equal(time(String(now / 1000), 'numeric-string', now), now);
assert.equal(time(now, 'milliseconds', now), now);
assert.equal(time(now + 120000, 'future', now), now);
assert.equal(time(now + 120000, 'future', now + 65000), now, 'Age must not reset when host clock approaches a future VM timestamp');
assert.equal(time(now + 5000, 'slightly-ahead', now), now, 'Even short clock skew must not freeze age at zero');
assert.equal(time('invalid', 'invalid', now), null);
assert.equal(time(undefined, 'missing', now), null);
console.log('Activity timestamp checks passed.');
