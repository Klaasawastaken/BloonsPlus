const assert=require('node:assert/strict'), fs=require('node:fs'), vm=require('node:vm');
const {failureResponseView}=require('../lib/failure-view');
const failure={at:'2026-10-06',map:'test',gamemode:'hard',route:'test.btd6',lastRound:24,finalRound:80,reason:'defeat',category:'gameplay-defeat',actionable:false,fullLog:['A'.repeat(50000)],log:['B'],actions:[{pos:[1,2]}],observations:[{}],screenshot:'private-frame.png'};
const body={available:true,total:614,categoryCounts:{'gameplay-defeat':347},routeSummary:[{attempts:2}],failures:[failure]};
assert.equal(failureResponseView(body,false),body);
const compact=failureResponseView(body,true);
assert.equal(compact.total,614);
assert.equal(compact.failures[0].lastRound,24);
for(const field of ['fullLog','log','actions','observations','screenshot']) assert.equal(Object.hasOwn(compact.failures[0],field),false,field);
assert.equal(body.failures[0].fullLog[0].length,50000);
assert.ok(JSON.stringify(compact).length < JSON.stringify(body).length / 50);
assert.deepEqual(failureResponseView({available:false},true).failures,[]);
const app=fs.readFileSync('assets/app/app.js','utf8');
const helper=app.slice(app.indexOf('function formatRouteFailures('),app.indexOf('async function loadRouteFailures()'));
const ctx={failures:[failure]};
assert.ok(vm.runInNewContext(helper+';formatRouteFailures(failures)',ctx).includes('round 24/80'));
assert.ok(!vm.runInNewContext(helper+';formatRouteFailures(failures)',ctx).includes('AAA'));
assert.ok(vm.runInNewContext(helper+';formatRouteFailures(failures,true)',ctx).includes('A'.repeat(50000)));
const server=fs.readFileSync('server.js','utf8');
assert.ok(server.includes("vmFetch('/api/route-failures' + (compact ? '?view=ui' : ''), compact ? 5000 : 45000)"));
assert.ok(app.includes("fetch('/api/route-failures?view=ui'"));
assert.ok(app.includes('formatRouteFailures(body.failures || [], true)'));
console.log('Compact failure view retains summaries; full export and original evidence remain intact.');
