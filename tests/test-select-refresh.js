const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(process.argv[2] || 'assets/app/select-controls.js', 'utf8');
const signature = source.slice(source.indexOf('  function signature('), source.indexOf('  function options('));
const sync = source.slice(source.indexOf('  function sync('), source.indexOf('  function enhance('));
const option = () => ({ value: 'hard', textContent: 'Hard', selected: true, disabled: false, hidden: false, parentElement: {} });
const nativeOption = option();
const select = { options: [nativeOption], selectedOptions: [nativeOption], isConnected: true, disabled: false,
  matches: selector => selector === ':disabled' && select.disabled };
let rebuilds = 0;
const control = { select, label: 'Difficulty', text: {}, button: { setAttribute() {} }, menu: { querySelector: () => null }, optionNodes: [nativeOption] };
const context = { opened: control, options: () => { rebuilds++; }, close: () => { throw Error('Unexpected close'); }, control };
vm.createContext(context);
vm.runInContext(signature + sync + 'control.signature = signature(control.select); sync(control);', context);
assert.equal(rebuilds, 0, 'unchanged options must not rebuild');
nativeOption.value = 'alternate';
vm.runInContext('sync(control)', context);
assert.equal(rebuilds, 1, 'changed native values must refresh open rows');
nativeOption.value = 'hard';
select.options = [option()];
select.selectedOptions = select.options;
vm.runInContext('sync(control)', context);
assert.equal(rebuilds, 2, 'identical replacement nodes must refresh detached row handlers');
console.log('Dropdown value and native-option replacement checks passed');
