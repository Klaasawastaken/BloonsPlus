const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('lib/automation.js','utf8');
const functions=source.slice(source.indexOf('function routeCandidatePriority('),source.indexOf('function getRecordedCombos('));
const context={};
vm.runInNewContext(functions+';this.compare=compareRouteCandidates',context);
const entry=(filename,changes={})=>({filename,resolution:'1920x1080',localWinVerified:false,isOriginalGamemode:false,...changes});
const dedicated=entry('glacial_trail#hard#spike-target-preserved.btd6',{isOriginalGamemode:true,converted:true});
const reused=entry('glacial_trail#chimps#spike-target-preserved.btd6',{reusedFromChimps:true,converted:true});
assert.equal([reused,dedicated].sort(context.compare)[0],dedicated);
assert.equal([entry('recorded-chimps',{reusedFromChimps:true}),dedicated].sort(context.compare)[0],dedicated);
const confirmed=entry('confirmed-fallback',{reusedFromChimps:true,converted:true,localWinVerified:true});
assert.equal([dedicated,confirmed].sort(context.compare)[0],confirmed);
const recorded=entry('recorded-hard',{isOriginalGamemode:true});
assert.equal([dedicated,recorded].sort(context.compare)[0],recorded);
const guide=entry('guide-hard',{isOriginalGamemode:true,onlineGuideSource:'known-guide'});
assert.equal([reused,guide].sort(context.compare)[0],guide);
const highRes=entry('high',{isOriginalGamemode:true,converted:true,resolution:'2560x1440'});
assert.equal([dedicated,highRes].sort(context.compare)[0],highRes);
assert.ok(source.includes('entries.sort(compareRouteCandidates)'));
console.log('Dedicated target routes precede reuse; exact wins and stable resolution order remain.');
